# creating list
see_world = ['south korea', 'hawaii', 'california', 'nigeria', 'england']

print(see_world)

# printing sorted list
print(sorted(see_world))

# showing list is still in original order
print(see_world)

# reversing the order of list
see_world.reverse()
print(see_world)

# reversing list back to it's original order
see_world.reverse()
print(see_world)

# sorting list in alphabetical order
see_world.sort()
print(see_world)

# sorting list in reverse alphabetical order
see_world.sort(reverse=True)
print(see_world)